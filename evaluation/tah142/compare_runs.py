"""Case-by-case comparison of the TAH-142 runs with their baselines (read-only over saved runs).

Usage, from ``backend/`` with the saved runs in the repository root:
    PYTHONPATH=. python ../evaluation/tah142/compare_runs.py > ../evaluation/tah142/case_comparison.md
"""

import importlib.util
import json
import re
import statistics
from collections import Counter
from pathlib import Path

from app.rag.evaluation.runner import DETERMINISTIC_REFUSALS, is_refusal, load_dataset

ROOT = Path(__file__).resolve().parents[2]
V3 = "app/rag/evaluation/generalization_v3.json"
SETS = {
    "historical": (
        "historical",
        ["consistency-7", "consistency-8", "consistency-9"],
        ["consistency-10", "consistency-11", "consistency-12"],
    ),
    "v1": (
        "generalization",
        ["gen-q1", "gen-q2", "gen-q3"],
        ["gen-s1", "gen-s2", "gen-s3"],
    ),
    "v2": (
        "generalization-v2",
        ["gen2-q1", "gen2-q2", "gen2-q3"],
        ["gen2-s1", "gen2-s2", "gen2-s3"],
    ),
    "v3": (
        V3,
        ["blind-v3-1", "blind-v3-2", "blind-v3-3"],
        ["blind-v3-s1", "blind-v3-s2", "blind-v3-s3"],
    ),
}
COMPLETE = {"sql_list", "sql_aggregate", "no_match"}
FACT_METRICS = ("financial_fact", "payment_identification", "completeness")
NON_ANSWERS = {"partial", "backend refusal", "model refusal"}

spec = importlib.util.spec_from_file_location(
    "fact_check", ROOT / "evaluation/blind_v3/fact_check.py"
)
fact_check = importlib.util.module_from_spec(spec)
spec.loader.exec_module(fact_check)
v3_cases = {
    c["id"]: c
    for c in json.loads((ROOT / "backend" / V3).read_text(encoding="utf-8"))["cases"]
}


def list_size_matches(case: dict, answer: str) -> bool:
    found = re.search(r"(?:Ho trovato|I found) (\d+)", answer)
    facts = [f for reading in case["golden"]["readings"] for f in reading["facts"]]
    sizes = [len(f["ids"]) for f in facts if "ids" in f] + [
        f["count"] for f in facts if "count" in f
    ]
    return not sizes or (found is not None and int(found.group(1)) in sizes)


def fact(dataset: str, result: dict) -> str:
    if dataset == "v3":
        verdict = fact_check.judge(v3_cases[result["id"]], result)[0]
        if (
            verdict == "pass"
            and result["route"] == "sql_list"
            and not result["used_llm"]
        ):
            return (
                "pass"
                if list_size_matches(v3_cases[result["id"]], result["answer"] or "")
                else "fail"
            )
        return verdict
    values = [
        result["metrics"][k]
        for k in FACT_METRICS
        if result["metrics"].get(k) not in (None, "not_applicable")
    ]
    return (
        "n/a" if not values else "pass" if all(v == "pass" for v in values) else "fail"
    )


def kind(dataset: str, result: dict) -> str:
    verdict, route, llm = fact(dataset, result), result["route"], result["used_llm"]
    refused = is_refusal(result["answer"] or "")
    if not llm and route in COMPLETE:
        return "FALSE complete (backend)" if verdict == "fail" else "complete"
    if not llm and route == "sql_partial":
        return "partial"
    if not llm and route in DETERMINISTIC_REFUSALS:
        return "backend refusal"
    if llm and refused:
        return "model refusal"
    if llm and verdict == "fail":
        return "model wrong"
    return "model" if llm else route


def main() -> None:
    print("# TAH-142: case-by-case comparison with the baselines\n")
    print(
        "Generated by `evaluation/tah142/compare_runs.py` from the saved runs. Kinds: `complete` (backend answer, every"
    )
    print(
        "constraint applied, judged correct), `FALSE complete (backend)` (wrong figure, false absence or list for another"
    )
    print(
        "question presented as complete), `partial` (labelled partial answer), `backend refusal` (clarify, unsupported,"
    )
    print(
        "unrecognised set, not recorded), `model` / `model wrong` / `model refusal` (Qwen). v3 uses `fact_check.py` plus a"
    )
    print("list-size check; the other datasets use the runner's fact metrics.\n")
    for dataset, (name, base, new) in SETS.items():
        cases = {c.id: c for c in load_dataset(name).cases}
        runs = {
            n: {
                r["id"]: r
                for r in json.loads(
                    (ROOT / f"rag_eval_phase_{n}.json").read_text(encoding="utf-8")
                )["results"]
            }
            for n in base + new
        }
        print(
            f"## {dataset}: {len(cases)} cases, baseline {', '.join(base)}, TAH-142 {', '.join(new)}\n"
        )
        print(
            "| Run | Passed | False complete (backend) | Complete | Partial | Backend refusal | Model wrong | Latency mean (s) |"
        )
        print("|---|---|---|---|---|---|---|---|")
        for n in base + new:
            kinds = Counter(kind(dataset, r) for r in runs[n].values())
            latency = statistics.mean(r["latency_ms"] for r in runs[n].values()) / 1000
            passed = sum(r["passed"] for r in runs[n].values())
            print(
                f"| {n} | {passed} | {kinds['FALSE complete (backend)']} | {kinds['complete']} | {kinds['partial']} | {kinds['backend refusal']} | {kinds['model wrong']} | {latency:.2f} |"
            )
        print("\n| Case | Passed base → new | Route base → new | Kind base → new |")
        print("|---|---|---|---|")
        for cid in cases:
            b = [runs[n][cid] for n in base]
            t = [runs[n][cid] for n in new]
            pb = "".join("P" if r["passed"] else "F" for r in b)
            pt = "".join("P" if r["passed"] else "F" for r in t)
            kb = sorted({kind(dataset, r) for r in b})
            kt = sorted({kind(dataset, r) for r in t})
            rb = sorted({r["route"] for r in b})
            rt = sorted({r["route"] for r in t})
            if pb == pt and kb == kt and rb == rt:
                continue
            print(
                f"| `{cid}` | {pb} → {pt} | {', '.join(rb)} → {', '.join(rt)} | {', '.join(kb)} → {', '.join(kt)} |"
            )
        print()


if __name__ == "__main__":
    main()
