#!/usr/bin/env bash
# Local end-to-end check of the Docker Compose deployment (Stripe TEST mode, Ollama on the host).
# Usage: ./scripts/smoke_local.sh            (from the repository root, with .env configured)
set -euo pipefail

API="http://127.0.0.1:8000"
OLLAMA="${OLLAMA_HOST_URL:-http://127.0.0.1:11434}"
CHAT_MODEL="${OLLAMA_CHAT_MODEL:-qwen2.5:7b-instruct}"
EMBED_MODEL="${OLLAMA_EMBED_MODEL:-$(sed -n 's/^OLLAMA_EMBED_MODEL=//p' .env 2>/dev/null | tr -d '"')}"
EMBED_MODEL="${EMBED_MODEL:-bge-m3}"
PASS=0
FAIL=0

ok() { echo "  PASS  $1"; PASS=$((PASS + 1)); }
ko() { echo "  FAIL  $1"; FAIL=$((FAIL + 1)); }
json() { python3 -c "import json,sys; d=json.load(sys.stdin); print($1)"; }

[ -f .env ] || { echo ".env missing: cp .env.example .env and set the sk_test_/whsec_ values"; exit 2; }
grep -qE '^STRIPE_SECRET_KEY=(sk|rk)_test_' .env || { echo "STRIPE_SECRET_KEY must be a test key"; exit 2; }

echo "1. Ollama on the host"
if curl -fsS "$OLLAMA/api/version" >/dev/null; then ok "Ollama reachable at $OLLAMA"; else ko "Ollama not running (ollama serve)"; fi
for model in "$CHAT_MODEL" "$EMBED_MODEL"; do
  if curl -fsS "$OLLAMA/api/tags" | grep -qF -e "\"$model\"" -e "\"$model:latest\""; then ok "model $model present"; else ko "model $model missing (ollama pull $model)"; fi
done

echo "2. Stack"
docker compose up -d --build db api reconciler qdrant rag-indexer dashboard
for _ in $(seq 1 60); do curl -fsS "$API/health" >/dev/null 2>&1 && break; sleep 2; done
if curl -fsS "$API/health" >/dev/null; then ok "api healthy"; else ko "api not healthy"; docker compose logs --tail=50 api; exit 1; fi

echo "3. RAG dependencies seen from the containers"
health=$(curl -sS "$API/rag/health")
echo "     $health"
[ "$(echo "$health" | json 'd["status"]')" = "ok" ] && ok "rag health" || ko "rag health"

echo "4. Merchant and checkout"
key=$(docker compose exec -T api python -m app.merchants.cli create "Smoke $(date +%s)" 2>/dev/null | sed -n 's/^api_key=//p')
[ -n "$key" ] && ok "merchant created" || { ko "merchant creation"; exit 1; }
op="smoke-$(date +%s)"
status=$(curl -sS -o /tmp/payflow_checkout.json -w '%{http_code}' -X POST "$API/payments/checkout" \
  -H "Authorization: Bearer $key" -H "Idempotency-Key: $op" -H 'content-type: application/json' \
  -d '{"product_id":"payflow-pro"}')
[ "$status" = "201" ] && ok "checkout created ($(json 'd["status"]' </tmp/payflow_checkout.json))" || ko "checkout returned $status"
replay=$(curl -sS -o /dev/null -w '%{http_code}' -X POST "$API/payments/checkout" \
  -H "Authorization: Bearer $key" -H "Idempotency-Key: $op" -H 'content-type: application/json' \
  -d '{"product_id":"payflow-pro"}')
[ "$replay" = "200" ] && ok "idempotent replay" || ko "replay returned $replay"

echo "5. Index and ask"
docker compose exec -T rag-indexer python -m app.rag.index && ok "index pass" || ko "index pass"
payment_id=$(json 'd.get("payment_id","")' </tmp/payflow_checkout.json)
answer=$(curl -sS -X POST "$API/rag/ask" -H "Authorization: Bearer $key" -H 'content-type: application/json' \
  -d "{\"question\":\"Qual è lo stato del pagamento $payment_id e quanto costa?\"}")
echo "$answer" | python3 -m json.tool
[ "$(echo "$answer" | json 'd.get("used_llm")')" = "True" ] && ok "answer generated by Qwen" || ko "no LLM answer"
echo "$answer" | grep -q "payment:$payment_id" && ok "own payment retrieved" || ko "own payment not retrieved"

echo "6. Dashboard"
DASH="http://127.0.0.1:8080"
for _ in $(seq 1 30); do curl -fsS "$DASH/" >/dev/null 2>&1 && break; sleep 2; done
[ "$(curl -s -o /dev/null -w '%{http_code}' "$DASH/payments")" = "200" ] && ok "dashboard serves the SPA" || ko "dashboard not reachable"
curl -sI "$DASH/" | grep -qi "content-security-policy: default-src 'self'" && ok "CSP header" || ko "CSP header missing"
[ "$(curl -s -o /dev/null -w '%{http_code}' -H "Authorization: Bearer $key" "$DASH/api/payments/stats")" = "200" ] \
  && ok "dashboard proxies /api to the api" || ko "api proxy"
[ "$(curl -s -o /dev/null -w '%{http_code}' -X POST "$DASH/api/webhooks/stripe")" = "404" ] \
  && ok "webhooks not exposed through the dashboard" || ko "webhook path exposed"

rm -f /tmp/payflow_checkout.json
echo
echo "Result: $PASS passed, $FAIL failed"
[ "$FAIL" -eq 0 ]
